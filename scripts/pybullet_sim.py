"""
Vortexa Studio - PyBullet Simulation Script Generator
"""

def generate_pybullet_script(urdf_filename: str = "vortexa_robot.urdf") -> str:
    """Return a ready-to-run PyBullet script that loads the given URDF."""
    script = f'''#!/usr/bin/env python3
"""
Auto-generated by Vortexa Studio
PyBullet physics validation script
"""

import time
import pybullet as p
import pybullet_data


def run_simulation(urdf_path: str = "{urdf_filename}", gui: bool = True):
    mode = p.GUI if gui else p.DIRECT
    p.connect(mode)
    p.setAdditionalSearchPath(pybullet_data.getDataPath())
    p.setGravity(0, 0, -9.81)
    p.setRealTimeSimulation(0)

    # Ground plane
    p.loadURDF("plane.urdf")

    # Robot
    start_pos = [0, 0, 0.05]
    start_ori = p.getQuaternionFromEuler([0, 0, 0])
    robot_id = p.loadURDF(urdf_path, start_pos, start_ori, useFixedBase=True)

    print(f"[Vortexa] Loaded {{urdf_path}} as body id {{robot_id}}")
    print("[Vortexa] Running 5 second validation simulation...")

    for i in range(5 * 240):
        p.stepSimulation()
        time.sleep(1.0 / 240.0)

    # Print basic joint info
    n_joints = p.getNumJoints(robot_id)
    print(f"[Vortexa] Robot has {{n_joints}} joints")
    for j in range(n_joints):
        info = p.getJointInfo(robot_id, j)
        print(f"  Joint {{j}}: {{info[1].decode()}} type={{info[2]}}")

    p.disconnect()
    print("[Vortexa] Simulation finished cleanly.")


if __name__ == "__main__":
    run_simulation()
'''
    return script
