"""
Vortexa Studio - URDF Generator
Produces standards-compliant Unified Robot Description Format XML.
Includes proper joint definitions, parent-child tree, and approximate inertias.
"""

from __future__ import annotations

from typing import Sequence, Dict, Any, List
from scripts.rigidbody_dynamics import RigidBodyDynamics


def generate_urdf(
    topology: Sequence[Dict[str, Any]],
    robot_name: str = "vortexa_robot",
    include_materials: bool = True,
) -> str:
    """
    Compile a Vortexa topology into a valid URDF string.

    Key industry requirements addressed:
    - Explicit parent-child joint tree
    - Proper joint types (fixed, revolute, continuous, prismatic)
    - Axis vectors
    - Approximate but physically plausible inertial parameters
    - Visual geometry
    - Basic collision geometry
    """
    if not topology:
        raise ValueError("Topology cannot be empty")

    # Build quick lookup and ensure ordered parent-child
    links = list(topology)
    name_to_link = {link.get("name", f"link_{i}"): link for i, link in enumerate(links)}

    # Compute better inertias
    dyn = RigidBodyDynamics(links)
    inertias = {item["name"]: item for item in dyn.link_inertias()}

    lines: List[str] = [
        '<?xml version="1.0"?>',
        f'<robot name="{robot_name}">',
        "",
        "  <!-- Generated by Vortexa Studio v3.5 -->",
        "  <!-- Validate this URDF in Gazebo / Isaac / your target toolchain -->",
        "",
    ]

    if include_materials:
        lines.extend([
            '  <material name="aluminum">',
            '    <color rgba="0.7 0.7 0.75 1"/>',
            "  </material>",
            '  <material name="carbon">',
            '    <color rgba="0.15 0.15 0.15 1"/>',
            "  </material>",
            '  <material name="titanium">',
            '    <color rgba="0.6 0.65 0.7 1"/>',
            "  </material>",
            '  <material name="plastic">',
            '    <color rgba="0.9 0.6 0.2 1"/>',
            "  </material>",
            '  <material name="steel">',
            '    <color rgba="0.45 0.47 0.5 1"/>',
            "  </material>",
            '  <material name="abs">',
            '    <color rgba="0.25 0.7 0.95 1"/>',
            "  </material>",
            "",
        ])

    # Emit all links first
    for link in links:
        name = link.get("name", "unnamed_link")
        mass = float(link.get("mass", 1.0))
        length = float(link.get("length", 0.3))
        radius = float(link.get("radius", 0.05))
        material = link.get("material", "aluminum").lower().replace(" ", "_").replace("+", "")
        if material not in ("aluminum", "carbon", "titanium", "plastic", "steel", "abs"):
            material = "aluminum"

        inertia = inertias.get(name, {
            "ixx": 0.01, "iyy": 0.01, "izz": 0.01,
            "ixy": 0.0, "ixz": 0.0, "iyz": 0.0,
        })

        # Center of mass roughly at mid-link for a cylinder
        com_z = length / 2.0

        lines.append(f'  <link name="{name}">')
        lines.append("    <inertial>")
        lines.append(f'      <origin xyz="0 0 {com_z:.6f}" rpy="0 0 0"/>')
        lines.append(f'      <mass value="{mass:.6f}"/>')
        lines.append(
            f'      <inertia ixx="{inertia["ixx"]:.8f}" ixy="{inertia["ixy"]:.8f}" '
            f'ixz="{inertia["ixz"]:.8f}" iyy="{inertia["iyy"]:.8f}" '
            f'iyz="{inertia["iyz"]:.8f}" izz="{inertia["izz"]:.8f}"/>'
        )
        lines.append("    </inertial>")
        lines.append("    <visual>")
        lines.append(f'      <origin xyz="0 0 {com_z:.6f}" rpy="0 0 0"/>')
        lines.append("      <geometry>")
        lines.append(f'        <cylinder radius="{radius:.6f}" length="{length:.6f}"/>')
        lines.append("      </geometry>")
        lines.append(f'      <material name="{material}"/>')
        lines.append("    </visual>")
        col = link.get("collision") or {}
        col_r = float(col.get("radius", radius * 1.05))
        col_l = float(col.get("length", length * 1.02))
        lines.append("    <collision>")
        lines.append(f'      <origin xyz="0 0 {com_z:.6f}" rpy="0 0 0"/>')
        lines.append("      <geometry>")
        lines.append(f'        <cylinder radius="{col_r:.6f}" length="{col_l:.6f}"/>')
        lines.append("      </geometry>")
        lines.append("    </collision>")
        lines.append("  </link>")
        lines.append("")

    # Emit joints (skip the root which has parent=null)
    for i, link in enumerate(links):
        parent_id = link.get("parent")
        if parent_id is None:
            continue  # root link

        # Resolve parent name
        parent_link = None
        for cand in links:
            if cand.get("id") == parent_id or cand.get("name") == parent_id:
                parent_link = cand
                break
        if parent_link is None and isinstance(parent_id, int) and 0 <= parent_id < len(links):
            parent_link = links[parent_id]

        if parent_link is None:
            # Fallback: previous link
            parent_link = links[i - 1] if i > 0 else None
        if parent_link is None:
            continue

        parent_name = parent_link.get("name", "base")
        child_name = link.get("name", f"link_{i}")
        joint_type = link.get("type", "revolute")
        if joint_type not in ("fixed", "revolute", "continuous", "prismatic"):
            joint_type = "revolute"

        axis = link.get("axis", "z")
        axis_vec = {"x": "1 0 0", "y": "0 1 0", "z": "0 0 1"}.get(axis, "0 0 1")

        # Joint origin: place at the end of the parent link
        parent_length = float(parent_link.get("length", 0.3))
        origin_xyz = f"0 0 {parent_length:.6f}"

        joint_name = f"{parent_name}_to_{child_name}"

        lines.append(f'  <joint name="{joint_name}" type="{joint_type}">')
        lines.append(f'    <parent link="{parent_name}"/>')
        lines.append(f'    <child link="{child_name}"/>')
        lines.append(f'    <origin xyz="{origin_xyz}" rpy="0 0 0"/>')
        lines.append(f'    <axis xyz="{axis_vec}"/>')

        if joint_type in ("revolute", "prismatic"):
            lim = link.get("limit") or {}
            if joint_type == "revolute":
                lo = float(lim.get("lower", -3.1416))
                hi = float(lim.get("upper", 3.1416))
                eff = float(lim.get("effort", 100.0))
                vel = float(lim.get("velocity", 2.0))
            else:
                lo = float(lim.get("lower", 0.0))
                hi = float(lim.get("upper", 0.3))
                eff = float(lim.get("effort", 50.0))
                vel = float(lim.get("velocity", 0.5))
            lines.append(
                f'    <limit lower="{lo:.6f}" upper="{hi:.6f}" effort="{eff:.3f}" velocity="{vel:.3f}"/>'
            )

        lines.append("  </joint>")
        lines.append("")

    lines.append("</robot>")
    return "\n".join(lines)
