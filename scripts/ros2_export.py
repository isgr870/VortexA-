"""
Vortexa Studio - ROS 2 package exporter
Generates a minimal ament_cmake package skeleton with URDF.
"""
from __future__ import annotations
from typing import Sequence, Dict, Any
from scripts.urdf_generator_api import generate_urdf


def generate_ros2_package(
    topology: Sequence[Dict[str, Any]],
    robot_name: str = "vortexa_robot",
    package_name: str | None = None,
) -> Dict[str, str]:
    """Return dict filename -> content for a minimal ROS 2 robot package."""
    pkg = package_name or f"{robot_name}_description"
    urdf = generate_urdf(topology, robot_name=robot_name)

    package_xml = f"""<?xml version="1.0"?>
<package format="3">
  <name>{pkg}</name>
  <version>0.1.0</version>
  <description>Robot description generated by Vortexa Studio</description>
  <maintainer email="user@vortexa.local">Vortexa User</maintainer>
  <license>Apache-2.0</license>
  <buildtool_depend>ament_cmake</buildtool_depend>
  <exec_depend>robot_state_publisher</exec_depend>
  <exec_depend>joint_state_publisher_gui</exec_depend>
  <exec_depend>rviz2</exec_depend>
  <export>
    <build_type>ament_cmake</build_type>
  </export>
</package>
"""

    cmake = f"""cmake_minimum_required(VERSION 3.8)
project({pkg})
find_package(ament_cmake REQUIRED)
install(DIRECTORY urdf launch DESTINATION share/${{PROJECT_NAME}})
ament_package()
"""

    launch_py = f'''from launch import LaunchDescription
from launch_ros.actions import Node
from ament_index_python.packages import get_package_share_directory
import os

def generate_launch_description():
    pkg = get_package_share_directory("{pkg}")
    urdf_file = os.path.join(pkg, "urdf", "{robot_name}.urdf")
    with open(urdf_file, "r") as f:
        robot_desc = f.read()
    return LaunchDescription([
        Node(
            package="robot_state_publisher",
            executable="robot_state_publisher",
            parameters=[{{"robot_description": robot_desc}}],
        ),
        Node(
            package="joint_state_publisher_gui",
            executable="joint_state_publisher_gui",
        ),
    ])
'''

    readme = f"""# {pkg}

Generated by Vortexa Studio.

## Build
```bash
cd ~/ros2_ws/src
# copy this package folder here
cd ~/ros2_ws && colcon build --packages-select {pkg}
source install/setup.bash
ros2 launch {pkg} display.launch.py
```
"""

    return {
        f"{pkg}/package.xml": package_xml,
        f"{pkg}/CMakeLists.txt": cmake,
        f"{pkg}/urdf/{robot_name}.urdf": urdf,
        f"{pkg}/launch/display.launch.py": launch_py,
        f"{pkg}/README.md": readme,
    }
